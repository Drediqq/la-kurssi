# exit if shit hits the fan
set -e

# get directory
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
echo "=> Repo path : $REPO_DIR"

# make script executable
echo "=> executing peasants..."
